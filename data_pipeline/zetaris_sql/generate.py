"""Generate the Zetaris SQL files for EDGAR, Eurostat, the risk views and the role grants.

Usage:
    uv run python -m data_pipeline.zetaris_sql.generate          # write the files
    uv run python -m data_pipeline.zetaris_sql.generate --check  # exit 1 if a file is stale

Inputs are data_pipeline/suppliers.yaml (public suppliers, CIKs, revenue tags) and the six
site countries. The ERP datasource file (10_) is hand-written because it carries a password
placeholder that the user fills in the Zetaris SQL Editor.

Lightning SQL rules: one statement per call (the runner splits on semicolons), no trailing
semicolon sent, explicit columns, no SELECT *. Only the views in container `risk` are ever
queried by the app.
"""

import argparse
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from data_pipeline.suppliers import COUNTRIES, Supplier, load_suppliers

SQL_DIR = Path(__file__).resolve().parent
USER_AGENT_PLACEHOLDER = "YOUR_APP_NAME YOUR_CONTACT_EMAIL"
ERP = "erp_pg"
EDGAR_DB, EDGAR_CONTAINER = "SR_EDGAR", "sr_edgar"
EUROSTAT_DB, EUROSTAT_CONTAINER = "SR_EUROSTAT", "sr_eurostat"
RISK_CONTAINER = "risk"
EDGAR_CONCEPT_URL = "https://data.sec.gov/api/xbrl/companyconcept/CIK{cik}/us-gaap/{tag}.json"
EUROSTAT_DATA_URL = "https://ec.europa.eu/eurostat/api/dissemination/statistics/1.0/data"
# Ten years of monthly history is plenty for 6-month trends and keeps responses small.
EUROSTAT_SINCE = "2015-01"
# REST tables are named after the revenue tag: when a tag changes, the new table gets a new
# name, so `run_sql.py --skip-exists` cannot keep the stale one, and nothing is ever dropped.
# The per-supplier views keep their names and are replaced in place.
TAG_SLUGS = {
    "Revenues": "revenues",
    "RevenueFromContractWithCustomerExcludingAssessedTax": "rfc_excl_tax",
    "RevenueFromContractWithCustomerIncludingAssessedTax": "rfc_incl_tax",
}
GENERATED_NOTE = (
    "-- Generated by data_pipeline/zetaris_sql/generate.py. Do not edit by hand:\n"
    "-- change the generator or data_pipeline/suppliers.yaml, then regenerate.\n"
)


@dataclass(frozen=True)
class Indicator:
    """One Eurostat indicator, fetched per country.

    Attributes:
        name: Indicator name used in risk.v_country_indicators.
        dataset: Eurostat dataset code.
        filters: Query filters that pin every dimension except geo and time to one value.
        description: Short description for comments and docs.
    """

    name: str
    dataset: str
    filters: str
    description: str


@dataclass(frozen=True)
class RiskView:
    """One app-facing view in container risk.

    Attributes:
        name: View name.
        date_column: Column whose range the verification reports, if any.
        roles: Zetaris roles granted SELECT on the view.
    """

    name: str
    date_column: str | None
    roles: tuple[str, ...]


INDICATORS = (
    Indicator(
        "unemployment_rate",
        "une_rt_m",
        "sex=T&age=TOTAL&unit=PC_ACT&s_adj=SA",
        "unemployment rate, % of labour force, monthly, seasonally adjusted",
    ),
    # prc_hicp_manr stopped at 2025-12; prc_hicp_minr (ECOICOP ver. 2) continues the series.
    Indicator(
        "hicp_annual_rate",
        "prc_hicp_minr",
        "coicop18=TOTAL&unit=RCH_A",
        "HICP all items, annual rate of change in %, monthly",
    ),
)

BOTH = ("buyer", "risk_manager")
RISK = ("risk_manager",)
RISK_VIEWS = (
    RiskView("v_suppliers_full", None, RISK),
    RiskView("v_suppliers_buyer", None, BOTH),
    RiskView("v_open_orders_full", "due_date", RISK),
    RiskView("v_open_orders_buyer", "due_date", BOTH),
    RiskView("v_part_sourcing", None, BOTH),
    RiskView("v_deliveries", "promised_date", BOTH),
    RiskView("v_contracts_full", "end_date", RISK),
    RiskView("v_supplier_revenue", "period_end", RISK),
    RiskView("v_country_indicators", "period", BOTH),
)
# CREATE ROLE ... DESCRIBE BY accepts only letters, digits and _ . - , (no spaces, no colons).
ROLES = (
    ("buyer", "Category_buyers,buyer_views_without_prices_or_contract_values"),
    ("risk_manager", "Risk_managers_and_directors,all_risk_views"),
)


def _public(suppliers: Sequence[Supplier]) -> list[Supplier]:
    return [s for s in suppliers if s.cik is not None]


def _edgar_view(supplier: Supplier) -> str:
    return f"{supplier.supplier_id.lower()}_revenue"


def _edgar_table(supplier: Supplier) -> str:
    if supplier.revenue_tag is None:
        raise ValueError(f"{supplier.supplier_id} has no revenue tag (private supplier)")
    return f"{supplier.supplier_id.lower()}_{TAG_SLUGS[supplier.revenue_tag]}_facts"


def _eurostat_table(indicator: Indicator, country: str) -> str:
    return f"{indicator.dataset}_{country.lower()}"


def _union(branches: Sequence[str]) -> str:
    return "\nUNION ALL\n".join(branches)


# --- 20: EDGAR -------------------------------------------------------------------------------


def edgar_create_sql(suppliers: Sequence[Supplier]) -> str:
    """Return 20_edgar_suppliers_create.sql: one REST table and one view per public supplier."""
    parts = [
        GENERATED_NOTE,
        "-- Source: SEC EDGAR XBRL companyconcept API (pattern of the getting-started recipe\n"
        "-- 01_edgar_company_facts_create.sql), one REST table and one flattened view per public\n"
        "-- supplier, with the revenue tag verified by scripts/verify_ciks.py.\n"
        "-- Terms: declared User-Agent required (the runner fills the placeholder from\n"
        "-- ZETARIS_USER_AGENT), at most 10 requests/s, query live, no bulk redistribution.\n"
        "-- Run one statement at a time (run_sql.py --skip-exists). On HTTP 429 wait 60 s and\n"
        "-- run the file once more with --skip-exists; created objects are skipped.\n"
        "-- REST tables carry the tag in their name and views are CREATE OR REPLACE, so a tag\n"
        "-- change adds a new table and repoints the view; nothing is dropped. Tables of a\n"
        "-- replaced tag can be removed by hand in the Data Explorer.\n",
        f"CREATE LIGHTNING DATABASE {EDGAR_DB} DESCRIBE BY "
        f'"SEC EDGAR revenue facts of the public suppliers";\n',
        f"CREATE SCHEMASTORE CONTAINER {EDGAR_CONTAINER};\n",
    ]
    for s in _public(suppliers):
        view, table = _edgar_view(s), _edgar_table(s)
        url = EDGAR_CONCEPT_URL.format(cik=s.cik, tag=s.revenue_tag)
        parts.append(
            f"-- {s.supplier_id} {s.name}, CIK {s.cik}, us-gaap {s.revenue_tag}\n"
            f"CREATE LIGHTNING REST TABLE {table} FROM {EDGAR_DB} REQUEST(\n"
            f'    endpoint "{url}",\n'
            '    method "get",\n'
            '    response_type "json",\n'
            '    http_encoding "URLENCODED"\n'
            ") HEADER (\n"
            f'    user-agent "{USER_AGENT_PLACEHOLDER}"\n'
            ") BODY ();\n"
        )
        parts.append(
            f"CREATE OR REPLACE SCHEMASTORE VIEW {view} WITH CONTAINER {EDGAR_CONTAINER} AS\n"
            "SELECT\n"
            "    cik,\n"
            "    tag AS concept,\n"
            "    fact.`start` AS period_start,\n"
            "    fact.`end` AS period_end,\n"
            "    fact.val AS value_usd,\n"
            "    fact.accn AS accession_number,\n"
            "    fact.fy AS fiscal_year,\n"
            "    fact.fp AS fiscal_period,\n"
            "    fact.frame AS period_frame,\n"
            "    fact.form AS form_type,\n"
            "    fact.filed AS filed_date\n"
            f"FROM {EDGAR_CONTAINER}.{table}\n"
            "LATERAL VIEW explode(units.USD) AS fact;\n"
        )
    return "\n".join(parts)


def edgar_select_sql(suppliers: Sequence[Supplier]) -> str:
    """Return 20_edgar_suppliers_select.sql: row count and period range per supplier view."""
    parts = [
        GENERATED_NOTE,
        "-- Each statement fetches one SEC endpoint live. Compare a count with\n"
        "--   curl -s -A <user agent> <endpoint> | jq '.units.USD | length'\n",
    ]
    for s in _public(suppliers):
        parts.append(
            f"SELECT COUNT(1) AS row_count, MIN(period_end) AS min_period_end, "
            f"MAX(period_end) AS max_period_end FROM {EDGAR_CONTAINER}.{_edgar_view(s)};\n"
        )
    return "\n".join(parts)


# --- 30: Eurostat ----------------------------------------------------------------------------


def eurostat_create_sql(countries: Sequence[str]) -> str:
    """Return 30_eurostat_countries_create.sql: one REST table and series view per pair."""
    parts = [
        GENERATED_NOTE,
        "-- Source: Eurostat dissemination API, JSON-stat 2.0 (pattern of the getting-started\n"
        "-- recipe 07_eurostat_create.sql). Every URL was tested with curl first: an invalid\n"
        "-- code does not fail, it returns an empty value object.\n"
        "-- Terms: Eurostat copyright notice, free re-use with attribution\n"
        "-- (https://ec.europa.eu/eurostat/about/policies/copyright). No key, no rate limit.\n"
        "-- Each query pins every dimension except time, so the value index is the time index.\n",
        f"CREATE LIGHTNING DATABASE {EUROSTAT_DB} DESCRIBE BY "
        f'"Eurostat indicators for the supplier site countries";\n',
        f"CREATE SCHEMASTORE CONTAINER {EUROSTAT_CONTAINER};\n",
    ]
    for country in countries:
        for ind in INDICATORS:
            table = _eurostat_table(ind, country)
            url = (
                f"{EUROSTAT_DATA_URL}/{ind.dataset}?format=JSON&geo={country}&{ind.filters}"
                f"&sinceTimePeriod={EUROSTAT_SINCE}&lang=EN"
            )
            parts.append(
                f"-- {country}: {ind.name} ({ind.dataset}), {ind.description}\n"
                f"CREATE LIGHTNING REST TABLE {table} FROM {EUROSTAT_DB} REQUEST(\n"
                f'    endpoint "{url}",\n'
                '    method "get",\n'
                '    response_type "json",\n'
                '    http_encoding "URLENCODED"\n'
                ") HEADER (\n"
                ") BODY ();\n"
            )
            parts.append(
                f"CREATE SCHEMASTORE VIEW {table}_series WITH CONTAINER {EUROSTAT_CONTAINER} AS\n"
                "SELECT\n"
                "    time_label AS period,\n"
                "    CAST(cell_value AS DOUBLE) AS indicator_value\n"
                f"FROM {EUROSTAT_CONTAINER}.{table}\n"
                "LATERAL VIEW explode(from_json(to_json(value), 'map<string,double>'))"
                " AS time_key, cell_value\n"
                "LATERAL VIEW explode(from_json(to_json(dimension.time.category.index),"
                " 'map<string,bigint>')) AS time_label, time_index_value\n"
                "WHERE CAST(time_key AS INT) = time_index_value;\n"
            )
    return "\n".join(parts)


def eurostat_select_sql(countries: Sequence[str]) -> str:
    """Return 30_eurostat_countries_select.sql: months and period range per series view."""
    parts = [GENERATED_NOTE]
    for country in countries:
        for ind in INDICATORS:
            parts.append(
                "SELECT COUNT(1) AS months, MIN(period) AS first_period, MAX(period) AS "
                f"last_period FROM {EUROSTAT_CONTAINER}.{_eurostat_table(ind, country)}_series;\n"
            )
    return "\n".join(parts)


# --- 40: risk views --------------------------------------------------------------------------


def _view(name: str, body: str) -> str:
    return (
        f"CREATE OR REPLACE SCHEMASTORE VIEW {name} WITH CONTAINER {RISK_CONTAINER} AS\n{body};\n"
    )


def _erp_views() -> list[str]:
    supplier_cols = (
        "    s.supplier_id,\n    s.name,\n    s.cik,\n    s.country_iso,\n    s.category,\n"
        "    s.site_lat,\n    s.site_lon,\n"
    )
    supplier_from = (
        f"FROM {ERP}.suppliers s\nLEFT JOIN {ERP}.contracts c ON c.supplier_id = s.supplier_id"
    )
    order_cols = (
        "    po.po_id,\n    po.supplier_id,\n    po.part_id,\n"
        "    p.description AS part_description,\n    p.criticality,\n    po.category,\n"
        "    po.qty,\n"
    )
    order_from = (
        f"FROM {ERP}.purchase_orders po\nJOIN {ERP}.parts p ON p.part_id = po.part_id\n"
        "WHERE po.status = 'open'"
    )
    return [
        "-- Suppliers with contract value and end date (risk managers only).\n"
        + _view(
            "v_suppliers_full",
            f"SELECT\n{supplier_cols}    c.annual_value_eur,\n"
            f"    c.end_date AS contract_end_date\n{supplier_from}",
        ),
        "-- Suppliers for buyers: contract end date, no contract value.\n"
        + _view(
            "v_suppliers_buyer",
            f"SELECT\n{supplier_cols}    c.end_date AS contract_end_date\n{supplier_from}",
        ),
        "-- Open purchase orders with unit price and order value (risk managers only).\n"
        + _view(
            "v_open_orders_full",
            f"SELECT\n{order_cols}    po.unit_price_eur,\n"
            "    CAST(po.qty * po.unit_price_eur AS DECIMAL(16, 2)) AS order_value_eur,\n"
            f"    po.due_date\n{order_from}",
        ),
        "-- Open purchase orders for buyers: no unit price and no order value (derived).\n"
        + _view("v_open_orders_buyer", f"SELECT\n{order_cols}    po.due_date\n{order_from}"),
        "-- Who supplies which part, with part criticality and single-source flag.\n"
        + _view(
            "v_part_sourcing",
            "SELECT\n    ps.part_id,\n    ps.supplier_id,\n"
            "    p.description AS part_description,\n    p.category,\n    p.criticality,\n"
            "    ps.share_pct,\n    ps.is_single_source\n"
            f"FROM {ERP}.part_sourcing ps\nJOIN {ERP}.parts p ON p.part_id = ps.part_id",
        ),
        "-- Deliveries per purchase order; days_late is NULL while the order is open.\n"
        + _view(
            "v_deliveries",
            "SELECT\n    d.po_id,\n    po.supplier_id,\n    po.part_id,\n    po.category,\n"
            "    po.status,\n    d.promised_date,\n    d.delivered_date,\n"
            "    datediff(d.delivered_date, d.promised_date) AS days_late\n"
            f"FROM {ERP}.deliveries d\nJOIN {ERP}.purchase_orders po ON po.po_id = d.po_id",
        ),
        "-- Contracts with buyer_notes (free text, untrusted; risk managers only).\n"
        + _view(
            "v_contracts_full",
            "SELECT\n    supplier_id,\n    annual_value_eur,\n    end_date,\n    buyer_notes\n"
            f"FROM {ERP}.contracts",
        ),
    ]


def _revenue_view(suppliers: Sequence[Supplier]) -> str:
    branches = [
        f"SELECT '{s.supplier_id}' AS supplier_id, '{s.cik}' AS cik, fiscal_year, fiscal_period,"
        " period_start, period_end, form_type, value_usd\n"
        f"FROM {EDGAR_CONTAINER}.{_edgar_view(s)}"
        for s in _public(suppliers)
    ]
    return (
        "-- EDGAR revenue facts per public supplier (supplier_id and CIK from suppliers.yaml).\n"
        "-- Raw fact history: a filing repeats earlier periods and 10-Ks hold quarterly facts,\n"
        "-- so callers pick periods by period_start/period_end, not by fiscal_year alone.\n"
        + _view("v_supplier_revenue", _union(branches))
    )


def _country_view(countries: Sequence[str]) -> str:
    branches = [
        f"SELECT '{country}' AS country_iso, '{ind.name}' AS indicator, period,"
        " indicator_value AS value\n"
        f"FROM {EUROSTAT_CONTAINER}.{_eurostat_table(ind, country)}_series"
        for country in countries
        for ind in INDICATORS
    ]
    return "-- Eurostat indicators per site country; period is YYYY-MM.\n" + _view(
        "v_country_indicators", _union(branches)
    )


def risk_views_create_sql(suppliers: Sequence[Supplier], countries: Sequence[str]) -> str:
    """Return 40_risk_views_create.sql: the only objects the app queries."""
    parts = [
        GENERATED_NOTE,
        "-- App-facing views in container risk. The app reads only these, with a role key:\n"
        "-- buyer views never carry unit prices, order values, contract values or notes.\n"
        "-- Row scope (the buyer's category) is a bound parameter in the tool layer.\n",
        f"CREATE SCHEMASTORE CONTAINER {RISK_CONTAINER};\n",
        *_erp_views(),
        _revenue_view(suppliers),
        _country_view(countries),
    ]
    return "\n".join(parts)


def risk_views_select_sql() -> str:
    """Return 40_risk_views_select.sql: row count and date range per risk view."""
    parts = [GENERATED_NOTE]
    for view in RISK_VIEWS:
        columns = "COUNT(1) AS row_count"
        if view.date_column:
            columns += f", MIN({view.date_column}) AS min_date, MAX({view.date_column}) AS max_date"
        parts.append(f"SELECT {columns} FROM {RISK_CONTAINER}.{view.name};\n")
    return "\n".join(parts)


# --- 60: roles and grants --------------------------------------------------------------------


def roles_grants_create_sql() -> str:
    """Return 60_roles_grants_create.sql (run by the user as admin after review)."""
    parts = [
        GENERATED_NOTE,
        "-- Roles and grants (docs/architecture.md 10.1). Run as admin in the SQL Editor after\n"
        "-- review; then follow docs/zetaris-setup.md (users, role assignment, masking, keys).\n"
        "-- director uses svc_risk (role risk_manager); auditor reads only the app database.\n",
    ]
    parts.extend(f"CREATE ROLE '{role}' DESCRIBE BY '{text}';\n" for role, text in ROLES)
    for role, _ in ROLES:
        parts.extend(
            f"GRANT SELECT ON VIEW TABLE {RISK_CONTAINER}.{view.name} TO ROLE '{role}';\n"
            for view in RISK_VIEWS
            if role in view.roles
        )
    return "\n".join(parts)


def roles_grants_select_sql() -> str:
    """Return 60_roles_grants_select.sql: show the roles and their grants."""
    lines = [GENERATED_NOTE, "SHOW ROLES;\n"]
    lines.extend(f"SHOW GRANT ROLE '{role}' ON ALL;\n" for role, _ in ROLES)
    return "\n".join(lines)


# --- entry point -----------------------------------------------------------------------------


def render_all() -> dict[str, str]:
    """Return every generated file as {file name: content}."""
    suppliers = load_suppliers()
    return {
        "20_edgar_suppliers_create.sql": edgar_create_sql(suppliers),
        "20_edgar_suppliers_select.sql": edgar_select_sql(suppliers),
        "30_eurostat_countries_create.sql": eurostat_create_sql(COUNTRIES),
        "30_eurostat_countries_select.sql": eurostat_select_sql(COUNTRIES),
        "40_risk_views_create.sql": risk_views_create_sql(suppliers, COUNTRIES),
        "40_risk_views_select.sql": risk_views_select_sql(),
        "60_roles_grants_create.sql": roles_grants_create_sql(),
        "60_roles_grants_select.sql": roles_grants_select_sql(),
    }


def main(argv: Sequence[str] | None = None) -> int:
    """Write the generated files, or with --check report stale ones.

    Args:
        argv: Command-line arguments (default: sys.argv[1:]).

    Returns:
        0 on success, 1 if --check found a missing or stale file.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare, write nothing")
    parser.add_argument("--out", type=Path, default=SQL_DIR, help="output directory")
    args = parser.parse_args(argv)
    stale = []
    for name, content in render_all().items():
        path = args.out / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(name)
        if not args.check:
            path.write_text(content, encoding="utf-8")
    if args.check and stale:
        sys.stderr.write("stale: " + ", ".join(stale) + "\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
